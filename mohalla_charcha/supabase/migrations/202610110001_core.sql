  bucket_id = 'post-media' AND (storage.foldername(name))[1] = auth.uid()::text
  AND lower(storage.extension(name)) IN ('jpg','jpeg','png','webp')
);
CREATE POLICY post_media_select ON storage.objects FOR SELECT TO authenticated USING (
  bucket_id = 'post-media' AND ((storage.foldername(name))[1] = auth.uid()::text OR
    EXISTS(SELECT 1 FROM public.posts p WHERE NOT p.is_hidden AND name = ANY(p.media_urls)))
);
CREATE POLICY post_media_delete_orphan ON storage.objects FOR DELETE TO authenticated USING (
  bucket_id = 'post-media' AND (storage.foldername(name))[1] = auth.uid()::text AND
    NOT EXISTS(SELECT 1 FROM public.posts p WHERE name = ANY(p.media_urls))
);
