-- Canonical location snapshots prevent a client forging a panchayat/ward path.
CREATE FUNCTION public._stamp_location() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE l public.bihar_locations;
BEGIN
  SELECT * INTO STRICT l FROM public.bihar_locations WHERE id = NEW.location_id;
  IF TG_TABLE_NAME = 'profiles' THEN NEW.primary_district := l.district;
  ELSE NEW.district := l.district;
    IF NEW.latitude IS NOT NULL THEN NEW.latitude := round(NEW.latitude::numeric, 3)::double precision; END IF;
    IF NEW.longitude IS NOT NULL THEN NEW.longitude := round(NEW.longitude::numeric, 3)::double precision; END IF;
  END IF;
  NEW.area_type := l.area_type; NEW.block_or_ulb := l.block_or_ulb;
  NEW.panchayat_name := l.panchayat_name; NEW.ward_number := l.ward_number;
  NEW.updated_at := now();
  RETURN NEW;
END $$;
CREATE TRIGGER profiles_location BEFORE INSERT OR UPDATE ON public.profiles FOR EACH ROW EXECUTE FUNCTION public._stamp_location();
CREATE TRIGGER posts_location BEFORE INSERT OR UPDATE ON public.posts FOR EACH ROW EXECUTE FUNCTION public._stamp_location();

CREATE FUNCTION public._guard_comment() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
DECLARE parent public.comments;
BEGIN
  IF NEW.parent_comment_id IS NULL THEN NEW.depth := 0;
  ELSE
    SELECT * INTO parent FROM public.comments WHERE id = NEW.parent_comment_id AND post_id = NEW.post_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'parent_comment_must_belong_to_same_post'; END IF;
    NEW.depth := parent.depth + 1;
    IF NEW.depth > 3 THEN RAISE EXCEPTION 'maximum_reply_depth_is_3'; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER comments_guard BEFORE INSERT ON public.comments FOR EACH ROW EXECUTE FUNCTION public._guard_comment();

-- Aggregate counters change in the SAME transaction as the authoritative rows.
CREATE FUNCTION public._reaction_counter() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE r public.post_reactions; delta integer;
BEGIN
  IF TG_OP = 'INSERT' THEN r := NEW; delta := 1; ELSE r := OLD; delta := -1; END IF;
  UPDATE public.posts SET
    upvotes_count = greatest(0, upvotes_count + CASE WHEN r.reaction_type = 'upvote' THEN delta ELSE 0 END),
    metadata = CASE
      WHEN r.reaction_type = 'ditto_problem' THEN jsonb_set(metadata, '{ditto_count}',
        to_jsonb(greatest(0, (metadata->>'ditto_count')::integer + delta)))
      WHEN r.reaction_type = 'rsvp_event' THEN jsonb_set(metadata, '{rsvp_count}',
        to_jsonb(greatest(0, (metadata->>'rsvp_count')::integer + delta)))
      ELSE metadata END
    WHERE id = r.post_id;
  RETURN r;
END $$;
CREATE TRIGGER reaction_counts AFTER INSERT OR DELETE ON public.post_reactions FOR EACH ROW EXECUTE FUNCTION public._reaction_counter();
CREATE FUNCTION public._comment_counter() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE c public.comments; delta integer;
BEGIN
  IF TG_OP = 'INSERT' THEN c := NEW; delta := 1; ELSE c := OLD; delta := -1; END IF;
  UPDATE public.posts SET comments_count = greatest(0, comments_count + delta) WHERE id = c.post_id;
  RETURN c;
END $$;
CREATE TRIGGER comment_counts AFTER INSERT OR DELETE ON public.comments FOR EACH ROW EXECUTE FUNCTION public._comment_counter();
CREATE FUNCTION public._report_counter() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE r public.post_reports; delta integer;
BEGIN
  IF TG_OP = 'INSERT' THEN r := NEW; delta := 1; ELSE r := OLD; delta := -1; END IF;
  UPDATE public.posts SET flag_count = greatest(0, flag_count + delta) WHERE id = r.post_id;
  -- Deliberately NO automatic hide: avoid community brigading/censorship.
  RETURN r;
END $$;
CREATE TRIGGER report_counts AFTER INSERT OR DELETE ON public.post_reports FOR EACH ROW EXECUTE FUNCTION public._report_counter();
CREATE FUNCTION public._sync_reputation() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN uid := OLD.user_id; ELSE uid := NEW.user_id; END IF;
  UPDATE public.profiles SET reputation_score = least(2147483647,
    (SELECT coalesce(sum(p.upvotes_count), 0) FROM public.posts p WHERE p.user_id = uid AND NOT p.is_hidden))::integer
    WHERE id = uid;
  RETURN NULL;
END $$;
CREATE TRIGGER post_reputation AFTER INSERT OR DELETE OR UPDATE OF upvotes_count, is_hidden ON public.posts
FOR EACH ROW EXECUTE FUNCTION public._sync_reputation();

