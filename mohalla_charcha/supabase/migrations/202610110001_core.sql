CREATE FUNCTION public._require_user() RETURNS uuid
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := auth.uid();
BEGIN
  IF uid IS NULL THEN RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '28000'; END IF;
  RETURN uid;
END $$;
CREATE FUNCTION public._require_profile() RETURNS uuid
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_user();
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = uid) THEN RAISE EXCEPTION 'complete_profile_first'; END IF;
  RETURN uid;
END $$;
CREATE FUNCTION public._rate_limit(p_action text, p_max integer, p_window_seconds integer) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_user(); start_at timestamptz; total integer;
BEGIN
  start_at := to_timestamp(floor(extract(epoch FROM clock_timestamp()) / p_window_seconds) * p_window_seconds);
  INSERT INTO public._rate_limits AS r(user_id, action, window_start, hits) VALUES (uid, p_action, start_at, 1)
  ON CONFLICT(user_id, action) DO UPDATE SET
    hits = CASE WHEN r.window_start = EXCLUDED.window_start THEN r.hits + 1 ELSE 1 END,
    window_start = EXCLUDED.window_start RETURNING hits INTO total;
  IF total > p_max THEN RAISE EXCEPTION 'rate_limit_exceeded'; END IF;
END $$;

-- Public identity explicitly excludes phone_number and private home landmark.
CREATE FUNCTION public._profile_card(p_uid uuid) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT jsonb_build_object('id', p.id, 'full_name', p.full_name, 'avatar_url', p.avatar_url,
    'reputation_score', p.reputation_score, 'location', to_jsonb(l) - 'geom')
  FROM public.profiles p JOIN public.bihar_locations l ON l.id = p.location_id WHERE p.id = p_uid;
$$;
CREATE FUNCTION public._post_json(p public.posts) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT (to_jsonb(p) - 'geom') || jsonb_build_object(
    'author', public._profile_card(p.user_id), 'location', to_jsonb(l) - 'geom',
    'viewer_reactions', (SELECT coalesce(jsonb_agg(r.reaction_type), '[]'::jsonb)
      FROM public.post_reactions r WHERE r.post_id = p.id AND r.user_id = auth.uid()),
    'viewer_reported', EXISTS(SELECT 1 FROM public.post_reports r WHERE r.post_id = p.id AND r.user_id = auth.uid()))
  FROM public.bihar_locations l WHERE l.id = p.location_id;
$$;
CREATE FUNCTION public._comment_json(c public.comments) RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT to_jsonb(c) || jsonb_build_object('author', public._profile_card(c.user_id));
$$;
CREATE FUNCTION public.get_own_profile() RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_user(); result jsonb;
BEGIN
  SELECT to_jsonb(p) || jsonb_build_object('location', to_jsonb(l) - 'geom') INTO result
  FROM public.profiles p JOIN public.bihar_locations l ON l.id = p.location_id WHERE p.id = uid;
  RETURN result;
END $$;

CREATE FUNCTION public.save_profile(p_name text, p_location_id bigint, p_landmark text DEFAULT '') RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_user(); phone text; l public.bihar_locations;
BEGIN
  PERFORM public._rate_limit('profile', 10, 900);
  IF p_name IS NULL OR length(btrim(p_name)) NOT BETWEEN 2 AND 100 OR
    p_landmark IS NULL OR length(p_landmark) > 150 THEN RAISE EXCEPTION 'invalid_profile_fields'; END IF;
  SELECT u.phone INTO phone FROM auth.users u WHERE u.id = uid AND u.phone_confirmed_at IS NOT NULL;
  IF phone IS NULL OR phone = '' THEN RAISE EXCEPTION 'verified_phone_required'; END IF;
  SELECT * INTO l FROM public.bihar_locations WHERE id = p_location_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'unknown_location'; END IF;
  INSERT INTO public.profiles(id, phone_number, full_name, location_id, primary_district,
    area_type, block_or_ulb, panchayat_name, ward_number, locality_landmark)
  VALUES(uid, phone, btrim(p_name), l.id, l.district, l.area_type, l.block_or_ulb, l.panchayat_name, l.ward_number, btrim(p_landmark))
  ON CONFLICT(id) DO UPDATE SET full_name = EXCLUDED.full_name, location_id = EXCLUDED.location_id,
    phone_number = EXCLUDED.phone_number, locality_landmark = EXCLUDED.locality_landmark;
  RETURN public.get_own_profile();
END $$;

CREATE FUNCTION public.create_post(p_type text, p_title text, p_description text, p_location_id bigint,
  p_metadata jsonb DEFAULT '{}', p_landmark text DEFAULT '', p_media_urls text[] DEFAULT '{}',
  p_latitude double precision DEFAULT NULL, p_longitude double precision DEFAULT NULL) RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile(); t public.post_type_enum;
  l public.bihar_locations; j jsonb; new_id uuid; path text;
BEGIN
  PERFORM public._rate_limit('post', 5, 900);
  t := p_type::public.post_type_enum;
  IF p_title IS NULL OR p_description IS NULL OR p_landmark IS NULL OR
    length(btrim(p_title)) NOT BETWEEN 5 AND 200 OR length(btrim(p_description)) NOT BETWEEN 10 AND 5000 OR
    length(p_landmark) > 150 THEN RAISE EXCEPTION 'invalid_post_fields'; END IF;
  SELECT * INTO l FROM public.bihar_locations WHERE id = p_location_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'unknown_location'; END IF;
  j := coalesce(p_metadata, '{}');
  IF t = 'civic_issue' THEN j := (j - ARRAY['is_resolved','ditto_count']) || '{"is_resolved":false,"ditto_count":0}'::jsonb;
  ELSIF t = 'event' THEN j := (j - 'rsvp_count') || '{"rsvp_count":0}'::jsonb;
  END IF;
  IF NOT public.valid_post_metadata(t, j) THEN RAISE EXCEPTION 'invalid_typed_metadata'; END IF;
  IF t = 'event' AND (j->>'event_date')::timestamptz <= now() THEN RAISE EXCEPTION 'event_date_must_be_in_future'; END IF;
  IF p_media_urls IS NULL OR cardinality(p_media_urls) > 3 THEN RAISE EXCEPTION 'maximum_3_images'; END IF;
  FOREACH path IN ARRAY p_media_urls LOOP
    IF path IS NULL OR split_part(path, '/', 1) <> uid::text OR
      NOT EXISTS(SELECT 1 FROM storage.objects o WHERE o.bucket_id = 'post-media' AND o.name = path) THEN
      RAISE EXCEPTION 'media_must_be_owned_storage_objects';
    END IF;
  END LOOP;
  INSERT INTO public.posts(user_id, post_type, title, description, location_id,
    district, area_type, block_or_ulb, panchayat_name, ward_number, locality_landmark,
    metadata, media_urls, latitude, longitude)
  VALUES(uid, t, btrim(p_title), btrim(p_description), l.id,
    l.district, l.area_type, l.block_or_ulb, l.panchayat_name, l.ward_number, btrim(p_landmark),
    j, p_media_urls, p_latitude, p_longitude) RETURNING id INTO new_id;
  RETURN new_id;
END $$;

CREATE FUNCTION public.get_feed(p_location_id bigint, p_scope text DEFAULT 'ward', p_type text DEFAULT NULL,
  p_search text DEFAULT '', p_sort text DEFAULT 'latest', p_limit integer DEFAULT 21,
  p_cursor_created timestamptz DEFAULT NULL, p_cursor_id uuid DEFAULT NULL,
  p_cursor_votes integer DEFAULT NULL) RETURNS SETOF jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE l public.bihar_locations; uid uuid := public._require_user();
BEGIN
  IF p_scope IS NULL OR p_scope NOT IN ('ward','area','block','district') OR
    p_sort IS NULL OR p_sort NOT IN ('latest','supported') OR
    (p_type IS NOT NULL AND p_type NOT IN ('civic_issue','local_review','event','general')) OR
    p_search IS NULL OR length(p_search) > 100 THEN RAISE EXCEPTION 'invalid_feed_query'; END IF;
  IF (p_cursor_id IS NULL) <> (p_cursor_created IS NULL) OR
    (p_sort = 'supported' AND p_cursor_id IS NOT NULL AND p_cursor_votes IS NULL) THEN RAISE EXCEPTION 'invalid_feed_cursor'; END IF;
  SELECT * INTO l FROM public.bihar_locations WHERE id = p_location_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'unknown_location'; END IF;
  RETURN QUERY SELECT public._post_json(p) FROM public.posts p WHERE NOT p.is_hidden
    AND p.district = l.district
    AND (p_scope = 'district' OR (p.area_type = l.area_type AND p.block_or_ulb = l.block_or_ulb
      AND (p_scope = 'block' OR p.panchayat_name IS NOT DISTINCT FROM l.panchayat_name)
      AND (p_scope <> 'ward' OR p.location_id = l.id)))
    AND (p_type IS NULL OR p.post_type::text = p_type)
    AND (btrim(p_search) = '' OR p.title ILIKE '%' || btrim(p_search) || '%' OR
      p.description ILIKE '%' || btrim(p_search) || '%' OR p.locality_landmark ILIKE '%' || btrim(p_search) || '%')
    AND (p_cursor_id IS NULL OR
      (p_sort = 'latest' AND (p.created_at, p.id) < (p_cursor_created, p_cursor_id)) OR
      (p_sort = 'supported' AND (p.upvotes_count, p.created_at, p.id) < (p_cursor_votes, p_cursor_created, p_cursor_id)))
    ORDER BY CASE WHEN p_sort = 'supported' THEN p.upvotes_count END DESC NULLS LAST,
      p.created_at DESC, p.id DESC LIMIT greatest(1, least(coalesce(p_limit, 21), 31));
END $$;

CREATE FUNCTION public.get_post(p_post_id uuid) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_user(); result jsonb;
BEGIN
  SELECT public._post_json(p) INTO result FROM public.posts p WHERE p.id = p_post_id AND NOT p.is_hidden;
  RETURN result;
END $$;
CREATE FUNCTION public.get_my_posts() RETURNS SETOF jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile();
BEGIN
  RETURN QUERY SELECT public._post_json(p) FROM public.posts p WHERE p.user_id = uid AND NOT p.is_hidden
    ORDER BY p.created_at DESC, p.id DESC LIMIT 100;
END $$;

CREATE FUNCTION public.set_reaction(p_post_id uuid, p_reaction text, p_active boolean) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile(); p public.posts; r public.reaction_type_enum;
BEGIN
  IF p_active IS NULL THEN RAISE EXCEPTION 'active_boolean_required'; END IF;
  PERFORM public._rate_limit('reaction', 120, 60);
  r := p_reaction::public.reaction_type_enum;
  SELECT * INTO p FROM public.posts WHERE id = p_post_id AND NOT is_hidden FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'post_unavailable'; END IF;
  IF (r = 'ditto_problem' AND p.post_type <> 'civic_issue') OR
    (r = 'rsvp_event' AND p.post_type <> 'event') THEN RAISE EXCEPTION 'reaction_does_not_match_post_type'; END IF;
  IF r = 'rsvp_event' AND p_active AND (p.metadata->>'event_date')::timestamptz <= now() THEN RAISE EXCEPTION 'event_has_ended'; END IF;
  IF p_active THEN INSERT INTO public.post_reactions(post_id, user_id, reaction_type) VALUES(p_post_id, uid, r)
    ON CONFLICT(post_id, user_id, reaction_type) DO NOTHING;
  ELSE DELETE FROM public.post_reactions WHERE post_id = p_post_id AND user_id = uid AND reaction_type = r;
  END IF;
END $$;

CREATE FUNCTION public.get_comments(p_post_id uuid) RETURNS SETOF jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_user();
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.posts WHERE id = p_post_id AND NOT is_hidden) THEN RAISE EXCEPTION 'post_unavailable'; END IF;
  RETURN QUERY SELECT public._comment_json(c) FROM public.comments c WHERE c.post_id = p_post_id
    ORDER BY c.created_at, c.id LIMIT 200;
END $$;
CREATE FUNCTION public.add_comment(p_post_id uuid, p_content text, p_parent_id uuid DEFAULT NULL) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile(); c public.comments;
BEGIN
  PERFORM public._rate_limit('comment', 30, 900);
  IF p_content IS NULL OR length(btrim(p_content)) NOT BETWEEN 1 AND 2000 THEN RAISE EXCEPTION 'reply_must_be_1_to_2000_characters'; END IF;
  PERFORM 1 FROM public.posts WHERE id = p_post_id AND NOT is_hidden FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'post_unavailable'; END IF;
  INSERT INTO public.comments(post_id, user_id, parent_comment_id, content)
    VALUES(p_post_id, uid, p_parent_id, btrim(p_content)) RETURNING * INTO c;
  RETURN public._comment_json(c);
END $$;
CREATE FUNCTION public.set_issue_resolution(p_post_id uuid, p_resolved boolean) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile();
BEGIN
  PERFORM public._rate_limit('resolution', 20, 900);
  IF p_resolved IS NULL THEN RAISE EXCEPTION 'resolved_boolean_required'; END IF;
  UPDATE public.posts SET metadata = jsonb_set(metadata, '{is_resolved}', to_jsonb(p_resolved))
    WHERE id = p_post_id AND user_id = uid AND post_type = 'civic_issue' AND NOT is_hidden;
  IF NOT FOUND THEN RAISE EXCEPTION 'only_author_can_resolve_civic_issue'; END IF;
END $$;
CREATE FUNCTION public.report_post(p_post_id uuid, p_reason text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile();
BEGIN
  PERFORM public._rate_limit('report', 10, 86400);
  IF p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 1 AND 300 THEN RAISE EXCEPTION 'invalid_report_reason'; END IF;
  PERFORM 1 FROM public.posts WHERE id = p_post_id AND NOT is_hidden AND user_id <> uid FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'post_unavailable_or_own_post'; END IF;
  INSERT INTO public.post_reports(post_id, user_id, reason) VALUES(p_post_id, uid, btrim(p_reason))
    ON CONFLICT(post_id, user_id) DO NOTHING;
END $$;
CREATE FUNCTION public.delete_post(p_post_id uuid) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile();
BEGIN
  DELETE FROM public.posts WHERE id = p_post_id AND user_id = uid;
  IF NOT FOUND THEN RAISE EXCEPTION 'only_author_can_delete_post'; END IF;
  -- Storage files become orphans. Remove using the scheduled cleanup worker.
END $$;
CREATE FUNCTION public.moderate_post(p_post_id uuid, p_hidden boolean, p_reason text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_profile();
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.community_moderators WHERE user_id = uid) THEN RAISE EXCEPTION 'community_moderator_required'; END IF;
  IF p_hidden IS NULL OR p_reason IS NULL OR length(btrim(p_reason)) NOT BETWEEN 3 AND 500 THEN RAISE EXCEPTION 'moderation_reason_required'; END IF;
  UPDATE public.posts SET is_hidden = p_hidden WHERE id = p_post_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'post_unavailable'; END IF;
  INSERT INTO public.moderation_log(post_id, actor_id, is_hidden, reason) VALUES(p_post_id, uid, p_hidden, btrim(p_reason));
END $$;
CREATE FUNCTION public.community_stats(p_location_id bigint) RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE uid uuid := public._require_user(); result jsonb;
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.bihar_locations WHERE id = p_location_id) THEN RAISE EXCEPTION 'unknown_location'; END IF;
  SELECT jsonb_build_object(
    'neighbours', (SELECT count(*) FROM public.profiles WHERE location_id = p_location_id),
    'open_issues', count(*) FILTER (WHERE p.post_type = 'civic_issue' AND NOT (p.metadata->>'is_resolved')::boolean),
    'resolved', count(*) FILTER (WHERE p.post_type = 'civic_issue' AND (p.metadata->>'is_resolved')::boolean),
    'events', count(*) FILTER (WHERE p.post_type = 'event' AND (p.metadata->>'event_date')::timestamptz > now())
  ) INTO result FROM public.posts p WHERE p.location_id = p_location_id AND NOT p.is_hidden;
  RETURN result;
END $$;

