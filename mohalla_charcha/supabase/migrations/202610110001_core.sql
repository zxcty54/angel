CREATE TABLE public.bihar_locations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  district varchar(50) NOT NULL CHECK (length(btrim(district)) > 0),
  area_type varchar(10) NOT NULL CHECK (area_type IN ('urban', 'rural')),
  block_or_ulb varchar(100) NOT NULL CHECK (length(btrim(block_or_ulb)) > 0),
  panchayat_name varchar(100),
  ward_number smallint NOT NULL CHECK (ward_number BETWEEN 1 AND 999),
  ward_alias varchar(150) NOT NULL DEFAULT '',
  latitude double precision,
  longitude double precision,
  geom extensions.geometry(Point, 4326) GENERATED ALWAYS AS (
    CASE WHEN latitude IS NOT NULL AND longitude IS NOT NULL
      THEN extensions.st_setsrid(extensions.st_makepoint(longitude, latitude), 4326) END
  ) STORED,
  CONSTRAINT location_branch CHECK (
    (area_type = 'urban' AND panchayat_name IS NULL) OR
    (area_type = 'rural' AND panchayat_name IS NOT NULL AND length(btrim(panchayat_name)) > 0)
  ),
  CONSTRAINT location_coordinates CHECK (
    (latitude IS NULL AND longitude IS NULL) OR
    (latitude IS NOT NULL AND longitude IS NOT NULL AND latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
  ),
  CONSTRAINT location_full_path UNIQUE NULLS NOT DISTINCT
    (district, area_type, block_or_ulb, panchayat_name, ward_number)
);
CREATE INDEX locations_district_catalogue ON public.bihar_locations(district, id);
CREATE INDEX locations_geom_gist ON public.bihar_locations USING gist(geom);

